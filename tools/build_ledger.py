#!/usr/bin/env python3
"""Regenerate LEDGER.md from ledger.tsv (scrub decisions), submissions.jsonl and agensi_status.json."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(ROOT, "ledger.tsv")) if l.strip()]
subs = {}
for l in open(os.path.join(ROOT, "submissions.jsonl")):
    r = json.loads(l)
    if r["status"] == "submitted": subs[r["skill"]] = r
status = json.load(open(os.path.join(ROOT, "agensi_status.json")))
by_url = {v["url"]: v for v in status.values()}
seen, listed, skipped = set(), [], []
for r in rows:
    r += [""] * (5 - len(r))
    name, src, dec, scrub, why = r[:5]
    if name in seen: continue
    seen.add(name)
    (listed if dec == "list" else skipped).append((name, src, scrub, why))
out = ["# Ledger", "",
       "Every global skill, repo-local skill and hook, what happened to it, and why. Generated by",
       "`tools/build_ledger.py` from `ledger.tsv`, `submissions.jsonl` and `agensi_status.json`.", "",
       f"Creator profile: https://agensi.io/creators/brick-mortar (display name \"Brick & Mortar\").", "",
       f"**Listed: {len(listed)} · Skipped: {len(skipped)}.** All listings are Free. Review status is as of the last",
       "`my_skills` read; a security status of `fail` is Agensi's automated scan (env var + network",
       "heuristics on tools that legitimately call an API with your own key) and goes to human review.", "",
       "## Listed", "",
       "| skill | source | listed | Agensi URL | review / scan | what was scrubbed |",
       "|---|---|---|---|---|---|"]
for name, src, scrub, _ in sorted(listed):
    s = subs.get(name, {})
    url = (s.get("detail") or {}).get("listing_url", "") if isinstance(s.get("detail"), dict) else ""
    st = by_url.get(url.replace("https://agensi.io", "https://agensi.io"), {})
    rs = f"{st.get('review','?')} / {st.get('security','?')}" if st else ("submitted" if s else "NOT SUBMITTED")
    out.append(f"| {name} | `{src}` | {'y' if s else 'n'} | {url} | {rs} | {scrub} |")
out += ["", "## Skipped", "", "| skill | source | listed | why skipped |", "|---|---|---|---|"]
for name, src, _, why in sorted(skipped):
    out.append(f"| {name} | `{src}` | n | {why} |")
out += ["", "## Resuming", "",
        "- `tools/submit.py <skill>...` gates, previews and confirms; it skips anything already `submitted` in",
        "  `submissions.jsonl`. OAuth token: `~/.config/agensi/oauth.json` (refreshes itself); account",
        "  credentials: `~/.config/agensi/credentials`. Neither is in this repo.",
        "- Refresh review status: `python3 tools/agensi.py my_skills`, then rerun this script.",
        "- Gate any folder: `tools/gate.sh skills/<name>` (zero hits or it does not list; reviewed false",
        "  positives live in `tools/allow.txt`)."]
open(os.path.join(ROOT, "LEDGER.md"), "w").write("\n".join(out) + "\n")
print(len(listed), "listed,", len(skipped), "skipped")
